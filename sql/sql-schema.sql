-- ============================================================
-- 1. USERS
-- Stores students, instructors, and administrators.
-- ============================================================

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    microsoft_id VARCHAR(255) UNIQUE,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    major VARCHAR(150),
    joined_year INTEGER,

    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash TEXT,
    profile_picture TEXT,

    role VARCHAR(20) NOT NULL
        CHECK (role IN ('student', 'instructor', 'admin')),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- A password is required unless Microsoft authentication
    -- is used. A user without a Microsoft ID needs a password.
    CONSTRAINT chk_users_authentication
        CHECK (microsoft_id IS NOT NULL OR password_hash IS NOT NULL)
);


-- ============================================================
-- 2. COURSES
-- Each course has exactly one instructor.
-- ============================================================

CREATE TABLE courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    instructor_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE RESTRICT,

    microsoft_class_id VARCHAR(255) UNIQUE,
    name VARCHAR(255) NOT NULL,
    academic_year VARCHAR(20) NOT NULL,

    semester VARCHAR(10) NOT NULL
        CHECK (semester IN ('fall', 'spring', 'summer')),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- ============================================================
-- 3. COURSE ENROLLMENTS
-- Many-to-many relationship between students and courses.
-- ============================================================

CREATE TABLE course_enrollments (
    student_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,

    course_id BIGINT NOT NULL
        REFERENCES courses(id) ON DELETE CASCADE,

    enrolled_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (student_id, course_id)
);


-- ============================================================
-- 4. PROJECTS
-- Each course can have at most one project.
-- ============================================================

CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    course_id BIGINT NOT NULL UNIQUE
        REFERENCES courses(id) ON DELETE CASCADE,

    min_members_per_team INTEGER NOT NULL,
    max_members_per_team INTEGER NOT NULL,
    prd TEXT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_project_min_members
        CHECK (min_members_per_team >= 1),

    CONSTRAINT chk_project_max_members
        CHECK (max_members_per_team >= min_members_per_team)
);


-- ============================================================
-- 5. TEAMS
-- A project can contain multiple teams.
-- Team names must be unique within their project.
-- ============================================================

CREATE TABLE teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    project_id BIGINT NOT NULL
        REFERENCES projects(id) ON DELETE CASCADE,

    name VARCHAR(150) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    feedback TEXT,

    CONSTRAINT uq_teams_project_name
        UNIQUE (project_id, name),

    -- Supports composite foreign keys for project-aware
    -- team membership validation.
    CONSTRAINT uq_teams_id_project
        UNIQUE (id, project_id)
);


-- ============================================================
-- 6. TEAM MEMBERS
-- Many-to-many relationship between students and teams.
-- A student may belong to only one team per project. --> this will be checked in the backend
-- ============================================================

CREATE TABLE team_members (
    team_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,

    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (team_id, student_id),

    CONSTRAINT fk_team_members_team
        FOREIGN KEY (team_id)
        REFERENCES teams(id)
        ON DELETE CASCADE
);


-- ============================================================
-- 7. TASKS
-- Each task belongs to one team and may have one assignee.
-- ============================================================

CREATE TABLE tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    team_id BIGINT NOT NULL
        REFERENCES teams(id) ON DELETE CASCADE,

    assignee_id BIGINT
        REFERENCES users(id) ON DELETE SET NULL,

    created_by BIGINT NOT NULL
        REFERENCES users(id) ON DELETE RESTRICT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    title VARCHAR(255) NOT NULL,
    due_date TIMESTAMPTZ,

    status VARCHAR(20) NOT NULL DEFAULT 'todo'
        CHECK (status IN ('todo', 'in_progress', 'review', 'done')),

    description TEXT
);


-- ============================================================
-- 8. SKILLS
-- Stores the available skills.
-- ============================================================

CREATE TABLE skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    category VARCHAR(20) NOT NULL
        CHECK (
            category IN (
                'interpersonal',
                'technical',
                'artistic',
                'linguistic',
                'other'
            )
        ),

    name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    created_by BIGINT
        REFERENCES users(id) ON DELETE SET NULL
);


-- ============================================================
-- 9. STUDENT SKILLS
-- Many-to-many relationship between students and skills.
-- ============================================================

CREATE TABLE student_skills (
    student_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,

    skill_id BIGINT NOT NULL
        REFERENCES skills(id) ON DELETE CASCADE,

    proficiency_level INTEGER NOT NULL,
    added_on TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (student_id, skill_id)
);


-- ============================================================
-- INDEXES
-- PostgreSQL automatically indexes primary keys and unique
-- constraints. These indexes help with foreign-key lookups.
-- ============================================================

CREATE INDEX idx_courses_instructor
    ON courses(instructor_id);

CREATE INDEX idx_course_enrollments_course
    ON course_enrollments(course_id);

CREATE INDEX idx_teams_project
    ON teams(project_id);

CREATE INDEX idx_team_members_student
    ON team_members(student_id);

CREATE INDEX idx_tasks_team
    ON tasks(team_id);

CREATE INDEX idx_tasks_assignee
    ON tasks(assignee_id);

CREATE INDEX idx_tasks_created_by
    ON tasks(created_by);

CREATE INDEX idx_skills_created_by
    ON skills(created_by);

CREATE INDEX idx_student_skills_skill
    ON student_skills(skill_id);


-- ============================================================
-- AUTOMATIC updated_at MAINTENANCE
-- ============================================================

CREATE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_users_updated_at
BEFORE UPDATE ON users
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_tasks_updated_at
BEFORE UPDATE ON tasks
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();


-- ============================================================
-- BUSINESS RULE 1
-- A student may belong to only one team within a project.
-- A transaction-level advisory lock helps serialize concurrent
-- membership changes for the same student.
-- ============================================================

CREATE FUNCTION check_student_project_team()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    target_project_id BIGINT;
BEGIN
    -- Serialize membership changes for this student.
    PERFORM pg_advisory_xact_lock(NEW.student_id);

    SELECT project_id
    INTO target_project_id
    FROM teams
    WHERE id = NEW.team_id;

    IF target_project_id IS NULL THEN
        RAISE EXCEPTION 'Team % does not exist', NEW.team_id;
    END IF;

    IF EXISTS (
        SELECT 1
        FROM team_members tm
        JOIN teams t ON t.id = tm.team_id
        WHERE tm.student_id = NEW.student_id
          AND t.project_id = target_project_id
          AND tm.team_id <> NEW.team_id
    ) THEN
        RAISE EXCEPTION
            'Student % already belongs to another team in project %',
            NEW.student_id,
            target_project_id;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_check_student_project_team
BEFORE INSERT OR UPDATE OF team_id, student_id
ON team_members
FOR EACH ROW
EXECUTE FUNCTION check_student_project_team();


-- ============================================================
-- BUSINESS RULE 2
-- An assigned task's assignee must be a student who belongs
-- to the team associated with that task.
-- ============================================================

CREATE FUNCTION check_task_assignee_membership()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    assignee_role VARCHAR(20);
BEGIN
    -- Unassigned tasks are permitted.
    IF NEW.assignee_id IS NULL THEN
        RETURN NEW;
    END IF;

    SELECT role
    INTO assignee_role
    FROM users
    WHERE id = NEW.assignee_id;

    IF assignee_role IS DISTINCT FROM 'student' THEN
        RAISE EXCEPTION
            'Task assignee % must be a student',
            NEW.assignee_id;
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM team_members
        WHERE team_id = NEW.team_id
          AND student_id = NEW.assignee_id
    ) THEN
        RAISE EXCEPTION
            'Assignee % is not a member of team %',
            NEW.assignee_id,
            NEW.team_id;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_check_task_assignee_membership
BEFORE INSERT OR UPDATE OF team_id, assignee_id
ON tasks
FOR EACH ROW
EXECUTE FUNCTION check_task_assignee_membership();

